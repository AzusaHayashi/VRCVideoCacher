<# Reproduces HookStatus.IsFresh: heartbeat < 90 s AND the pid is alive. #>
function Test-HookStatusFresh {
    param([Parameter(Mandatory=$true)]$Status)
    if ($null -eq $Status) { return $false }
    $heartbeat = [datetime]::Parse($Status.lastHeartbeatUtc).ToUniversalTime()
    if (((Get-Date).ToUniversalTime() - $heartbeat).TotalSeconds -gt 90) { return $false }
    try { $null = Get-Process -Id $Status.pid -ErrorAction Stop; return $true } catch { return $false }
}

