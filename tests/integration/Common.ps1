<#
.SYNOPSIS
    Shared helpers for the CookieBridge integration tests.

.DESCRIPTION
    PowerShell 5.1 and 7 compatible (no ternary, no ??, no -Parallel). Every artefact lives under the
    workspace: the sandbox used to drive these tests cannot write to %LOCALAPPDATA%/%APPDATA%, and the
    real user vault / real VRCVideoCacher cookie file must never be touched.

    Environment contract used by every test:
      VRCCB_ROOT          bridge root (vault, logs, state, disabled flag)
      VRCCB_TARGET_FILE   the "VRCVideoCacher cookie file" under test
      VRCCB_MOCK_COOKIE_PATH  what the mock host believes YtdlManager.CookiesPath is
      DOTNET_STARTUP_HOOKS    absolute path of CookieBridge.Hook.dll (only for injection tests)
#>

