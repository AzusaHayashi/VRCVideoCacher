function Initialize-Dotnet {
    $sdk = 'C:\Users\lz200\dotnet-sdk\sdk'
    if (Test-Path (Join-Path $sdk 'dotnet.exe')) {
        $env:PATH = "$sdk;$env:PATH"
    }
    $env:DOTNET_CLI_TELEMETRY_OPTOUT = '1'
    $env:DOTNET_NOLOGO = '1'
    $env:DOTNET_SKIP_FIRST_TIME_EXPERIENCE = '1'
    return (Get-Command dotnet -ErrorAction Stop).Source
}

function Invoke-Dotnet {
    param([Parameter(Mandatory=$true)][string[]]$Arguments, [string]$WorkingDirectory)
    $exe = Initialize-Dotnet
    $cwd = (Get-Location).Path
    if ($WorkingDirectory) { Set-Location $WorkingDirectory }
    try {
        $output = & $exe @Arguments 2>&1
        $code = $LASTEXITCODE
        return [pscustomobject]@{ ExitCode = $code; Output = ($output | Out-String) }
    } finally { Set-Location $cwd }
}

function New-TestRoot {
    param([Parameter(Mandatory=$true)][string]$Name)
    $root = Join-Path $script:WorkRoot $Name
    if (Test-Path $root) { Remove-Item $root -Recurse -Force -ErrorAction SilentlyContinue }
    New-Item -ItemType Directory -Path $root -Force | Out-Null
    return $root
}

<#
    Locates the newest build output matching a pattern. The Hook/Core TFM is not hard-coded: the team has
    moved it between net10.0 and net10.0-windows, and the integration tests must follow the real artefact.
#>
function Find-BuildArtifact {
    param([Parameter(Mandatory=$true)][string]$Pattern, [string]$Under)
    if (-not $Under) { $Under = (Join-Path $script:RepoRoot 'bridge') }
    $found = Get-ChildItem -Path $Under -Recurse -Filter $Pattern -File -ErrorAction SilentlyContinue |
             Where-Object { $_.FullName -notmatch '\\obj\\' } |
             Sort-Object LastWriteTime -Descending
    if (-not $found) { return $null }
    return $found[0].FullName
}

function Get-HookDllPath {
    $path = Find-BuildArtifact -Pattern 'CookieBridge.Hook.dll' -Under (Join-Path $script:RepoRoot 'bridge\CookieBridge.Hook\bin')
    if (-not $path) { throw 'CookieBridge.Hook.dll not found - build bridge/CookieBridge.Hook -c Release first' }
    return $path
}

function Get-NativeHostPath {
