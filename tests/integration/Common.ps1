<#
    Writes one length-prefixed native message to a process' stdin and reads the length-prefixed reply.
    Kept in one place so Test-01 and Test-06 use exactly the same framing implementation.
#>
function Invoke-NativeMessage {
    param(
        [Parameter(Mandatory=$true)][string]$HostExe,
        [Parameter(Mandatory=$true)][string]$Json,
        [hashtable]$Environment = @{},
        [int]$TimeoutMs = 20000
    )

    $psi = New-Object System.Diagnostics.ProcessStartInfo
    $psi.FileName = $HostExe
    $psi.UseShellExecute = $false
    $psi.RedirectStandardInput = $true
    $psi.RedirectStandardOutput = $true
    $psi.RedirectStandardError = $true
    $psi.CreateNoWindow = $true
    foreach ($key in $Environment.Keys) { $psi.EnvironmentVariables[$key] = [string]$Environment[$key] }

    $proc = New-Object System.Diagnostics.Process
    $proc.StartInfo = $psi
    [void]$proc.Start()

    $payload = [System.Text.Encoding]::UTF8.GetBytes($Json)
    $stdin = $proc.StandardInput.BaseStream
    $header = [BitConverter]::GetBytes([uint32]$payload.Length)
    $stdin.Write($header, 0, 4)
    $stdin.Write($payload, 0, $payload.Length)
    $stdin.Flush()

    $stdout = $proc.StandardOutput.BaseStream
    $readHeader = New-Object byte[] 4
    $read = 0
    while ($read -lt 4) {
        $n = $stdout.Read($readHeader, $read, 4 - $read)
        if ($n -le 0) { break }
        $read += $n
    }
    $reply = $null
    if ($read -eq 4) {
        $length = [BitConverter]::ToUInt32($readHeader, 0)
        $buffer = New-Object byte[] $length
        $got = 0
        while ($got -lt $length) {
            $n = $stdout.Read($buffer, $got, $length - $got)
            if ($n -le 0) { break }
            $got += $n
        }
        if ($got -eq $length) { $reply = [System.Text.Encoding]::UTF8.GetString($buffer) }
    }

    try { $proc.StandardInput.Close() } catch { }
    if (-not $proc.WaitForExit($TimeoutMs)) { try { $proc.Kill() } catch { } }
    $stderr = $proc.StandardError.ReadToEnd()
    $exitCode = $proc.ExitCode
    $proc.Dispose()

    return [pscustomobject]@{ Reply = $reply; ExitCode = $exitCode; Stderr = $stderr }
}

function New-CookieUpdateJson {
    param(
        [Parameter(Mandatory=$true)][string]$Cookies,
        [string]$Browser = 'chrome',
        [string]$ExtensionVersion = '1.2.0'
    )
    $obj = [ordered]@{
        type             = 'cookie.update'
        browser          = $Browser
        extensionVersion = $ExtensionVersion
        cookies          = $Cookies
        capturedUtc      = '2026-11-01T00:30:00Z'
    }
    return ($obj | ConvertTo-Json -Depth 5 -Compress)
}

# ---- process helpers --------------------------------------------------------

function Start-BridgeProcess {
    param(
        [Parameter(Mandatory=$true)][string]$FilePath,
        [string[]]$Arguments = @(),
        [hashtable]$Environment = @{}
    )
    $psi = New-Object System.Diagnostics.ProcessStartInfo
    $psi.FileName = $FilePath
    $psi.UseShellExecute = $false
    $psi.RedirectStandardOutput = $true
    $psi.RedirectStandardError = $true
    $psi.RedirectStandardInput = $false
    $psi.CreateNoWindow = $true
    foreach ($key in $Environment.Keys) { $psi.EnvironmentVariables[$key] = [string]$Environment[$key] }
    foreach ($a in $Arguments) { [void]$psi.ArgumentList.Add($a) }
    $proc = New-Object System.Diagnostics.Process
    $proc.StartInfo = $psi
    [void]$proc.Start()
    return $proc
}

<# Drains stdout/stderr of a background process into a string builder without blocking. #>
function Start-ProcessCollector {
    param([Parameter(Mandatory=$true)][System.Diagnostics.Process]$Process)
    $state = [pscustomobject]@{ StdOut = New-Object System.Text.StringBuilder; StdErr = New-Object System.Text.StringBuilder }
    $null = Register-ObjectEvent -InputObject $Process -EventName OutputDataReceived -Action {
        if ($EventArgs.Data) { $Event.MessageData.StdOut.AppendLine($EventArgs.Data) | Out-Null }
    } -MessageData $state
    $null = Register-ObjectEvent -InputObject $Process -EventName ErrorDataReceived -Action {
        if ($EventArgs.Data) { $Event.MessageData.StdErr.AppendLine($EventArgs.Data) | Out-Null }
    } -MessageData $state
    $Process.BeginOutputReadLine()
    $Process.BeginErrorReadLine()
    return $state
}

function Stop-ProcessTree {
    param([Parameter(Mandatory=$true)][int]$ProcessId)
    try {
        & taskkill.exe /PID $ProcessId /T /F 2>&1 | Out-Null
    } catch { }
}

function Wait-Until {
    param(
        [Parameter(Mandatory=$true)][scriptblock]$Condition,
        [int]$TimeoutSeconds = 20,
        [int]$PollMilliseconds = 200
    )
    $deadline = (Get-Date).AddSeconds($TimeoutSeconds)
    while ((Get-Date) -lt $deadline) {
        $result = $null
        try { $result = & $Condition } catch { $result = $null }
        if ($result) { return $result }
        Start-Sleep -Milliseconds $PollMilliseconds
    }
    return $null
}

