function Start-BridgeProcess {
    param(
        [Parameter(Mandatory=$true)][string]$FilePath,
        [string[]]$Arguments = @(),
        [hashtable]$Environment = @{},
        [string]$Tag = 'proc'
    )
    $io = Join-Path $script:WorkRoot '_io'
    New-Item -ItemType Directory -Path $io -Force | Out-Null
    $stamp = [guid]::NewGuid().ToString('N')
    $outFile = Join-Path $io "$Tag-$stamp.out"
    $errFile = Join-Path $io "$Tag-$stamp.err"

    $saved = @{}
    foreach ($key in $Environment.Keys) {
        $saved[$key] = [Environment]::GetEnvironmentVariable($key, 'Process')
        [Environment]::SetEnvironmentVariable($key, [string]$Environment[$key], 'Process')
    }

    try {
        $startArgs = @{
            FilePath               = $FilePath
            RedirectStandardOutput = $outFile
            RedirectStandardError  = $errFile
            NoNewWindow            = $true
            PassThru               = $true
        }
        if ($Arguments.Count -gt 0) { $startArgs['ArgumentList'] = ($Arguments -join ' ') }
        $proc = Start-Process @startArgs
    } finally {
        foreach ($key in $saved.Keys) {
            [Environment]::SetEnvironmentVariable($key, $saved[$key], 'Process')
        }
    }

    $proc | Add-Member -NotePropertyName StdOutFile -NotePropertyValue $outFile -Force
    $proc | Add-Member -NotePropertyName StdErrFile -NotePropertyValue $errFile -Force
    return $proc
}

function Get-ProcessStdOut {
    param([Parameter(Mandatory=$true)]$Process)
    $file = $Process.StdOutFile
    if ($file -and (Test-Path $file)) {
        $text = Get-Content -Raw $file
        if ($null -eq $text) { return '' }
        return [string]$text
    }
    return ''
}

function Get-ProcessStdErr {
    param([Parameter(Mandatory=$true)]$Process)
    $file = $Process.StdErrFile
    if ($file -and (Test-Path $file)) {
        $text = Get-Content -Raw $file
        if ($null -eq $text) { return '' }
        return [string]$text
    }
    return ''
}

<# Drains stdout/stderr of a background process into a string builder without blocking. #>
function Start-ProcessCollector {
    param([Parameter(Mandatory=$true)][System.Diagnostics.Process]$Process)
    $state = [pscustomobject]@{ StdOut = New-Object System.Text.StringBuilder; StdErr = New-Object System.Text.StringBuilder }
    $null = Register-ObjectEvent -InputObject $Process -EventName OutputDataReceived -Action {
        if ($EventArgs.Data) { $Event.MessageData.StdOut.AppendLine($EventArgs.Data) | Out-Null }
    } -MessageData $state
    $null = Register-ObjectEvent -InputObject $Process -EventName ErrorDataReceived -Action {
        if ($EventArgs.Data) { $Event.MessageData.StdErr.AppendLine($EventArgs.Data) | Out-Null }
    } -MessageData $state
    $Process.BeginOutputReadLine()
    $Process.BeginErrorReadLine()
    return $state
}

function Stop-ProcessTree {
    param([Parameter(Mandatory=$true)][int]$ProcessId)
    try {
        & taskkill.exe /PID $ProcessId /T /F 2>&1 | Out-Null
    } catch { }
}

function Wait-Until {
    param(
        [Parameter(Mandatory=$true)][scriptblock]$Condition,
        [int]$TimeoutSeconds = 20,
        [int]$PollMilliseconds = 200
    )
    $deadline = (Get-Date).AddSeconds($TimeoutSeconds)
    while ((Get-Date) -lt $deadline) {
        $result = $null
        try { $result = & $Condition } catch { $result = $null }
        if ($result) { return $result }
        Start-Sleep -Milliseconds $PollMilliseconds
    }
    return $null
}

