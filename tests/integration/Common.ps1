# ---- synthetic cookie jars (never real credentials) -------------------------

function New-TestCookieJar {
    param(
        [int]$ExtraCookies = 4,
        [string]$LoginValue = 'FAKE_LOGIN_INFO_do_not_use',
        [switch]$WithoutLogin,
        [switch]$WithStCookies
    )
    $expires = 1893456000   # 2030-01-01
    $lines = New-Object System.Collections.Generic.List[string]
    $lines.Add('# Netscape HTTP Cookie File')
    $lines.Add('# This file is generated by VRCVideoCacher.  Do not edit.')
    if (-not $WithoutLogin) {
        $lines.Add(".youtube.com`tTRUE`t/`tTRUE`t$expires`tLOGIN_INFO`t$LoginValue")
    }
    $lines.Add(".youtube.com`tTRUE`t/`tTRUE`t$expires`tSID`tFAKE_SID_VALUE")
    $lines.Add(".youtube.com`tTRUE`t/`tTRUE`t$expires`tHSID`tFAKE_HSID_VALUE")
    for ($i = 0; $i -lt $ExtraCookies; $i++) {
        $lines.Add(".youtube.com`tTRUE`t/`tTRUE`t$expires`tFAKE_COOKIE_$i`tFAKE_VALUE_$i")
    }
    if ($WithStCookies) {
        $lines.Add(".youtube.com`tTRUE`t/`tTRUE`t$expires`tST-FILTERME`tFAKE_ST_VALUE")
    }
    return ($lines -join "`n") + "`n"
}

function Get-JarCookieCount {
    param([Parameter(Mandatory=$true)][string]$Text)
    $count = 0
    foreach ($line in ($Text -split "`n")) {
        $l = $line.TrimEnd("`r")
        if ($l.Length -eq 0) { continue }
        if ($l.StartsWith('#HttpOnly_')) { $l = $l.Substring(11) }
        elseif ($l.StartsWith('#')) { continue }
        if (($l -split "`t").Count -ge 7) { $count++ }
    }
    return $count
}

