$script:CurrentTest = ''
$script:Checks = New-Object System.Collections.Generic.List[object]
$script:LogPath = Join-Path $script:WorkRoot 'last-test.log'

function Start-TestCase {
    param([Parameter(Mandatory=$true)][string]$Name)
    $script:CurrentTest = $Name
    $script:Checks = New-Object System.Collections.Generic.List[object]
    Write-Host ''
    Write-Host "=== $Name ===" -ForegroundColor Cyan
}

function Write-Check {
    param([Parameter(Mandatory=$true)][string]$Message, [bool]$Ok = $true, [string]$Detail = '')
    $script:Checks.Add([pscustomobject]@{ Name = $Message; Ok = $Ok; Detail = $Detail })
    if ($Ok) { Write-Host ("  [PASS] " + $Message) -ForegroundColor Green }
    else {
        Write-Host ("  [FAIL] " + $Message) -ForegroundColor Red
        if ($Detail) { Write-Host ("         " + $Detail) -ForegroundColor DarkYellow }
    }
}

function Assert-True {
    param([bool]$Condition, [string]$Message, [string]$Detail = '')
    Write-Check -Message $Message -Ok $Condition -Detail $Detail
}

function Assert-Equal {
    param($Expected, $Actual, [string]$Message)
    $ok = ([string]$Expected -eq [string]$Actual)
    Write-Check -Message $Message -Ok $ok -Detail ("expected=" + $Expected + " actual=" + $Actual)
}

function Assert-FileExists {
    param([string]$Path, [string]$Message)
    Write-Check -Message $Message -Ok (Test-Path $Path) -Detail ("missing: " + $Path)
}

function Assert-FileMissing {
    param([string]$Path, [string]$Message)
    Write-Check -Message $Message -Ok (-not (Test-Path $Path)) -Detail ("unexpectedly present: " + $Path)
}

function Complete-TestCase {
    $failed = @($script:Checks | Where-Object { -not $_.Ok })
    if ($failed.Count -eq 0) {
        Write-Host "RESULT $($script:CurrentTest): PASS ($($script:Checks.Count) checks)" -ForegroundColor Green
        return $true
    }
    Write-Host "RESULT $($script:CurrentTest): FAIL ($($failed.Count)/$($script:Checks.Count) checks failed)" -ForegroundColor Red
    return $false
}
