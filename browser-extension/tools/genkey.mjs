#!/usr/bin/env node
/**
 * browser-extension/tools/genkey.mjs — generate the Chrome MV3 unpacked-extension identity.
 *
 * Chrome derives an unpacked extension's ID from the public key shipped in manifest.json:
 *
 *   id = first 16 bytes of SHA-256(DER SubjectPublicKeyInfo of the RSA public key),
 *        each byte's two hex nibbles mapped 0-15 -> 'a'-'p'
 *
 * So one RSA-2048 keypair fixes the extension ID, which is what the native host's
 * `allowed_origins` needs. No dependencies: node:crypto + node:fs only.
 *
 * Usage:
 *   node browser-extension/tools/genkey.mjs            # print key + id, touch nothing
 *   node browser-extension/tools/genkey.mjs --write    # also update manifest.json "key"
 *                                                      # and extension-id.txt
 *   node browser-extension/tools/genkey.mjs --json      # machine readable stdout
 *
 * The private key is NEVER written to disk and never printed: Chrome only needs the
 * public half. Keep it only if you plan to package a .crx.
 */

import { createHash, createPublicKey, generateKeyPairSync } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const EXTENSION_DIR = join(HERE, "..");
const MANIFEST_PATH = join(EXTENSION_DIR, "manifest.json");
const ID_PATH = join(EXTENSION_DIR, "extension-id.txt");
const GECKO_ID = "vrexcookiebridge@local";

/**
 * Chrome extension id from a DER SPKI public key.
 * @param {Buffer} spkiDer
 * @returns {string} 32 chars in [a-p]
 */
export function extensionIdFromSpki(spkiDer) {
  const digest = createHash("sha256").update(spkiDer).digest();
  let id = "";
  for (const byte of digest.subarray(0, 16)) {
    id += String.fromCharCode(97 + (byte >> 4));
    id += String.fromCharCode(97 + (byte & 0x0f));
  }
  return id;
}

/**
 * Generate an RSA-2048 keypair and return the pieces the manifest needs.
 * @returns {{spkiDer: Buffer, keyBase64: string, extensionId: string, modulusBits: number}}
 */
export function generateManifestKey() {
  const { publicKey, privateKey } = generateKeyPairSync("rsa", {
    modulusLength: 2048,
    publicKeyEncoding: { type: "spki", format: "der" },
    privateKeyEncoding: { type: "pkcs8", format: "pem" },
  });

  // Sanity: the DER blob must round-trip through node's own key parser, and the
  // private half must actually belong to it.
  const publicKeyObject = createPublicKey({ key: publicKey, format: "der", type: "spki" });
  const modulusBits = publicKeyObject.asymmetricKeyDetails?.modulusLength ?? 0;
  if (modulusBits !== 2048) {
    throw new Error(`unexpected modulus length: ${modulusBits}`);
  }
  const fromPrivate = createPublicKey(privateKey).export({ type: "spki", format: "der" });
  if (!Buffer.from(fromPrivate).equals(Buffer.from(publicKey))) {
    throw new Error("private key does not match the generated public key");
  }

  return {
    spkiDer: Buffer.from(publicKey),
    keyBase64: Buffer.from(publicKey).toString("base64"),
    extensionId: extensionIdFromSpki(Buffer.from(publicKey)),
    modulusBits,
  };
}

function updateManifest(keyBase64) {
  const manifest = JSON.parse(readFileSync(MANIFEST_PATH, "utf8"));
  manifest.key = keyBase64;
  writeFileSync(MANIFEST_PATH, `${JSON.stringify(manifest, null, 2)}\n`, "utf8");
}

function writeExtensionIdFile(extensionId, keyBase64) {
  const body = [
    "# VRCVideoCacher CookieBridge — browser extension identity",
    "# generated by tools/genkey.mjs (do not hand edit)",
    "",
    `extension_id=${extensionId}`,
    `origin=chrome-extension://${extensionId}/`,
    `manifest_key=${keyBase64}`,
    `gecko_id=${GECKO_ID}`,
    "",
    "# Native host (com.vrcvideocacher.cookiebridge) must allow:",
    `#   Chrome  allowed_origins:    ["chrome-extension://${extensionId}/"]`,
    `#   Firefox allowed_extensions: ["${GECKO_ID}"]`,
    "",
  ].join("\n");
  writeFileSync(ID_PATH, body, "utf8");
}

function main(argv) {
  const write = argv.includes("--write");
  const asJson = argv.includes("--json");
  const { keyBase64, extensionId, modulusBits } = generateManifestKey();
  const origin = `chrome-extension://${extensionId}/`;

  if (write) {
    updateManifest(keyBase64);
    writeExtensionIdFile(extensionId, keyBase64);
  }

  if (asJson) {
    process.stdout.write(
      `${JSON.stringify(
        {
          extensionId,
          origin,
          geckoId: GECKO_ID,
          modulusBits,
          key: keyBase64,
          manifestUpdated: write,
          extensionIdFileWritten: write,
        },
        null,
        2,
      )}\n`,
    );
    return;
  }

  process.stdout.write(
    [
      `modulus bits   : ${modulusBits}`,
      `extension id   : ${extensionId}`,
      `origin         : ${origin}`,
      `gecko id       : ${GECKO_ID} (fixed via browser_specific_settings.gecko.id)`,
      "",
      "manifest.json \"key\" (add as a single line string):",
      keyBase64,
      "",
      write
        ? `wrote: ${MANIFEST_PATH} (key)\nwrote: ${ID_PATH}`
        : "nothing written (pass --write to update manifest.json and extension-id.txt)",
    ].join("\n") + "\n",
  );
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main(process.argv.slice(2));
}
