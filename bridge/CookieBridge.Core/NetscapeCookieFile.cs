using System.Security.Cryptography;
using System.Text;

namespace CookieBridge.Core;

/// <summary>One Netscape cookie row. Values are secret; never log a record.</summary>
public sealed record CookieRecord(
    string Domain,
    bool IncludeSubdomains,
    string Path,
    bool Secure,
    long ExpiresUnixSeconds,
    string Name,
    string Value)
{
    /// <summary>Row in the exact layout VRCVideoCacher / yt-dlp expect (7 tab separated fields).</summary>
    public string ToLine() => string.Join('\t',
        Domain,
        IncludeSubdomains ? "TRUE" : "FALSE",
        Path,
        Secure ? "TRUE" : "FALSE",
        ExpiresUnixSeconds.ToString(),
        Name,
        Value);

    public override string ToString() => $"Cookie({Domain}, {Path}, {Name}, len={Value.Length})";
}

/// <summary>Non-sensitive description of a cookie jar; safe to log, display and store in the vault.</summary>
public sealed record CookieSummary(
    int CookieCount,
    bool LoginCookiePresent,
    DateTimeOffset? EarliestExpiryUtc,
    DateTimeOffset? LatestExpiryUtc,
    bool HasYoutubeDomain,
    string Sha256)
{
    public static CookieSummary Empty { get; } =
        new(0, false, null, null, false, string.Empty);
}

/// <summary>
/// Netscape cookie-file handling shared by every component.
///
/// The rules mirror upstream VRCVideoCacher exactly:
///  * <c>ApiController.FilterCookies</c> drops names starting with <c>ST-</c> (breaks yt-dlp's
///    YouTube bot check).
///  * <c>Program.IsCookiesValid</c> accepts a jar only when it contains <c>youtube.com</c> and
///    <c>LOGIN_INFO</c>.
/// Keeping both here means the extension, the host and the hook can never disagree.
/// </summary>
public static class NetscapeCookieFile
{
    public const string Header =
        "# Netscape HTTP Cookie File\n# This file is generated by VRCVideoCacher.  Do not edit.\n";

    private const string HttpOnlyPrefix = "#HttpOnly_";

    public static IReadOnlyList<CookieRecord> Parse(string? text)
    {
        var result = new List<CookieRecord>();
        if (string.IsNullOrWhiteSpace(text)) return result;

        foreach (var raw in text.Split('\n'))
        {
            var line = raw.TrimEnd('\r');
            if (line.Length == 0) continue;

            var httpOnly = false;
            if (line.StartsWith(HttpOnlyPrefix, StringComparison.Ordinal))
            {
                httpOnly = true;
                line = line[HttpOnlyPrefix.Length..];
            }
            else if (line.StartsWith('#'))
            {
                continue; // real comment
            }

            var parts = line.Split('\t');
            if (parts.Length < 7) continue;

            var name = parts[5];
            if (name.Length == 0) continue;

            long expires = 0;
            _ = long.TryParse(parts[4], out expires);

            var domain = NormalizeDomain(parts[0]);
            if (domain.Length == 0) continue;

            var path = parts[2].Length == 0 ? "/" : parts[2];

            result.Add(new CookieRecord(
                domain,
                string.Equals(parts[1], "TRUE", StringComparison.OrdinalIgnoreCase),
                path,
                string.Equals(parts[3], "TRUE", StringComparison.OrdinalIgnoreCase),
                expires,
                name,
                parts[6]));
            _ = httpOnly;
        }

        return result;
    }

    /// <summary>
    /// Normalises a jar into the canonical form we persist and hand to VRCVideoCacher:
    /// <c>ST-*</c> rows removed, duplicates collapsed (last wins), header restored.
    /// </summary>
    public static string Canonicalize(string? text)
    {
        var records = Parse(text)
            .Where(r => !r.Name.StartsWith("ST-", StringComparison.Ordinal))
            .Where(r => r.Name.Length > 0);

        var seen = new Dictionary<string, CookieRecord>(StringComparer.Ordinal);
        var order = new List<string>();
        foreach (var record in records)
        {
            var key = Key(record);
            if (!seen.ContainsKey(key)) order.Add(key);
            seen[key] = record;
        }

        var sb = new StringBuilder(Header);
        foreach (var key in order)
            sb.Append(seen[key].ToLine()).Append('\n');

        return sb.ToString();
    }

    public static CookieSummary Summarize(string? canonicalText)
    {
        var records = Parse(canonicalText);
        if (records.Count == 0) return CookieSummary.Empty;

        var login = records.Any(r =>
            r.Name.Equals("LOGIN_INFO", StringComparison.Ordinal) && r.Domain.Contains("youtube.com", StringComparison.OrdinalIgnoreCase));

        var youtube = records.Any(r => r.Domain.Contains("youtube.com", StringComparison.OrdinalIgnoreCase));

        var now = DateTimeOffset.UtcNow.ToUnixTimeSeconds();
        var expiries = records
            .Where(r => r.ExpiresUnixSeconds > now)
            .Select(r => r.ExpiresUnixSeconds)
            .ToList();

        DateTimeOffset? earliest = expiries.Count > 0
            ? DateTimeOffset.FromUnixTimeSeconds(expiries.Min())
            : null;
        DateTimeOffset? latest = expiries.Count > 0
            ? DateTimeOffset.FromUnixTimeSeconds(expiries.Max())
            : null;

        return new CookieSummary(
            records.Count,
            login,
            earliest,
            latest,
            youtube,
            Sha256Hex(canonicalText ?? string.Empty));
    }

    /// <summary>Exact upstream acceptance test (<c>Program.IsCookiesValid</c>).</summary>
    public static bool IsValidForVrcvc(string? text) =>
        !string.IsNullOrEmpty(text)
        && text.Contains("youtube.com", StringComparison.Ordinal)
        && text.Contains("LOGIN_INFO", StringComparison.Ordinal);

    public static bool IsUsable(string? text) =>
        IsValidForVrcvc(text) && Parse(text).Count > 0;

    public static string Sha256Hex(string text)
    {
        var hash = SHA256.HashData(Encoding.UTF8.GetBytes(text));
        return Convert.ToHexStringLower(hash);
    }

    private static string NormalizeDomain(string domain)
    {
        var trimmed = domain.Trim();
        if (trimmed.Length == 0) return string.Empty;
        return trimmed.StartsWith('.') ? trimmed : "." + trimmed;
    }

    private static string Key(CookieRecord r) => string.Join('\u0001', r.Domain, r.Path, r.Name);
}
