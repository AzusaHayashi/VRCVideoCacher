using CookieBridge.Core;
using Xunit;

namespace CookieBridge.Tests;

[Collection(BridgeEnvironmentCollection.Name)]
public sealed class NetscapeCookieFileTests : BridgeTestBase
{
    private const string Header = "# Netscape HTTP Cookie File\n# This file is generated by VRCVideoCacher.  Do not edit.\n";

    // ---- Parse ----------------------------------------------------------

    [Fact]
    public void Parse_ReadsHttpOnlyRows_AndKeepsThemAsCookies()
    {
        var text = Header +
                   "#HttpOnly_.youtube.com\tTRUE\t/\tTRUE\t1893456000\t__Secure-1PSID\tFAKE_VALUE\n" +
                   ".youtube.com\tTRUE\t/\tTRUE\t1893456000\tLOGIN_INFO\tFAKE_LOGIN_INFO_VALUE\n";

        var records = NetscapeCookieFile.Parse(text);

        Assert.Equal(2, records.Count);
        Assert.Equal("__Secure-1PSID", records[0].Name);
        Assert.Equal(".youtube.com", records[0].Domain);
        Assert.Equal("FAKE_LOGIN_INFO_VALUE", records[1].Value);
    }

    [Fact]
    public void Parse_SkipsCommentLines()
    {
        var records = NetscapeCookieFile.Parse(
            Header +
            "# a plain comment\n" +
            "# another\twith\ttabs\tinside\n" +
            ".youtube.com\tTRUE\t/\tTRUE\t1893456000\tLOGIN_INFO\tvalue\n");

        Assert.Single(records);
        Assert.Equal("LOGIN_INFO", records[0].Name);
    }

    [Fact]
    public void Parse_SkipsRowsWithTooFewFields()
    {
        var text = Header +
                   ".youtube.com\tTRUE\t/\tTRUE\t1893456000\tSIX_FIELDS_ONLY\n" +   // 6 fields
                   ".youtube.com\tTRUE\t/\tTRUE\t1893456000\n" +                     // 5 fields
                   "garbage\n" +                                                    // 1 field
                   "\n" +                                                           // blank
                   ".youtube.com\tTRUE\t/\tTRUE\t1893456000\tLOGIN_INFO\tvalue\n";   // 7 fields

        var records = NetscapeCookieFile.Parse(text);

        Assert.Single(records);
        Assert.Equal("LOGIN_INFO", records[0].Name);
        Assert.Equal("value", records[0].Value);
    }

    [Fact]
    public void Parse_HandlesCrLf()
    {
        var text = (Header + ".youtube.com\tTRUE\t/\tTRUE\t1893456000\tLOGIN_INFO\tv\r\n" +
                            ".youtube.com\tTRUE\t/\tTRUE\t1893456000\tSID\tv2\r\n");

        var records = NetscapeCookieFile.Parse(text);

        Assert.Equal(2, records.Count);
        Assert.Equal("v", records[0].Value);          // no stray \r in the value
        Assert.Equal("v2", records[1].Value);
        Assert.Equal(".youtube.com", records[1].Domain);
    }

    [Fact]
    public void Parse_AddsLeadingDotToBareDomain()
    {
        var records = NetscapeCookieFile.Parse("youtube.com\tTRUE\t/\tTRUE\t1893456000\tLOGIN_INFO\tv\n");

        Assert.Single(records);
        Assert.Equal(".youtube.com", records[0].Domain);
    }

    [Fact]
    public void Parse_EmptyOrNull_ReturnsEmpty()
    {
        Assert.Empty(NetscapeCookieFile.Parse(null));
        Assert.Empty(NetscapeCookieFile.Parse(""));
        Assert.Empty(NetscapeCookieFile.Parse("   \n\n"));
    }

    [Fact]
    public void Parse_FlagsSecureAndIncludeSubdomains()
    {
        var records = NetscapeCookieFile.Parse(
            ".youtube.com\tFALSE\t/x\tFALSE\t1893456000\tA\t1\n" +
            ".youtube.com\ttrue\t/\ttrue\t1893456000\tB\t2\n");

        Assert.False(records[0].IncludeSubdomains);
        Assert.False(records[0].Secure);
        Assert.True(records[1].IncludeSubdomains);
        Assert.True(records[1].Secure);
    }

    // ---- Canonicalize ---------------------------------------------------

    [Fact]
    public void Canonicalize_DropsStPrefixedCookies()
    {
        var canonical = NetscapeCookieFile.Canonicalize(TestJars.Build() +
            TestJars.Row(".youtube.com", "ST-abcdef", "FAKE_ST_VALUE") + "\n" +
            TestJars.Row(".youtube.com", "STAPISID", "not-filtered") + "\n");

        Assert.DoesNotContain("\tST-abcdef\t", canonical);
        Assert.Contains("\tLOGIN_INFO\t", canonical);
        // Only the "ST-" prefix is filtered, exactly like upstream ApiController.FilterCookies.
        Assert.Contains("\tSTAPISID\t", canonical);
    }

    [Fact]
    public void Canonicalize_DeduplicatesByDomainPathName_LastWins_PreservingOrder()
    {
        var text = Header +
                   TestJars.Row(".youtube.com", "LOGIN_INFO", "first") + "\n" +
                   TestJars.Row(".youtube.com", "SID", "sid-value") + "\n" +
                   TestJars.Row(".youtube.com", "LOGIN_INFO", "second") + "\n";

        var canonical = NetscapeCookieFile.Canonicalize(text);
        var records = NetscapeCookieFile.Parse(canonical);

        Assert.Equal(2, records.Count);
        Assert.Equal("LOGIN_INFO", records[0].Name);      // original position kept
        Assert.Equal("second", records[0].Value);         // last value wins
        Assert.Equal("SID", records[1].Name);
    }

    [Fact]
    public void Canonicalize_AlwaysRestoresHeader_AndAddsDomainDot()
    {
        var canonical = NetscapeCookieFile.Canonicalize(
            "youtube.com\tTRUE\t/\tTRUE\t1893456000\tLOGIN_INFO\tv\n");

        Assert.StartsWith(NetscapeCookieFile.Header, canonical, StringComparison.Ordinal);
        Assert.Contains(".youtube.com\tTRUE\t/\tTRUE\t1893456000\tLOGIN_INFO\tv", canonical);
        Assert.EndsWith("\n", canonical, StringComparison.Ordinal);
    }

    [Fact]
    public void Canonicalize_IsIdempotent()
    {
        var once = NetscapeCookieFile.Canonicalize(TestJars.Build());
        var twice = NetscapeCookieFile.Canonicalize(once);

        Assert.Equal(once, twice);
    }

    [Fact]
    public void Canonicalize_EmptyInput_YieldsHeaderOnly()
    {
        Assert.Equal(NetscapeCookieFile.Header, NetscapeCookieFile.Canonicalize(null));
        Assert.Equal(NetscapeCookieFile.Header, NetscapeCookieFile.Canonicalize(""));
    }

    [Fact]
    public void Canonicalize_ProducesSevenTabSeparatedFields()
    {
        var canonical = NetscapeCookieFile.Canonicalize(TestJars.Build(extraCookies: 1));

        var rows = canonical.Split('\n').Where(l => l.Length > 0 && !l.StartsWith('#')).ToList();

        Assert.NotEmpty(rows);
        Assert.All(rows, row => Assert.Equal(7, row.Split('\t').Length));
    }

    // ---- IsValidForVrcvc: must match upstream Program.IsCookiesValid ----

    /// <summary>Verbatim copy of upstream VRCVideoCacher/Program.cs::IsCookiesValid (lines 249-259).</summary>
    private static bool UpstreamIsCookiesValid(string cookies)
    {
        if (string.IsNullOrEmpty(cookies)) return false;
        if (cookies.Contains("youtube.com") && cookies.Contains("LOGIN_INFO")) return true;
        return false;
    }

    [Theory]
    [InlineData(null)]
    [InlineData("")]
    [InlineData("no cookies here")]
    [InlineData(".youtube.com\tTRUE\t/\tTRUE\t1893456000\tPREF\tv\n")]      // no LOGIN_INFO
    [InlineData(".example.com\tTRUE\t/\tTRUE\t1893456000\tLOGIN_INFO\tv\n")]  // no youtube.com
    public void IsValidForVrcvc_Rejects_ExactlyLikeUpstream(string? text)
    {
        Assert.False(NetscapeCookieFile.IsValidForVrcvc(text));
        Assert.Equal(UpstreamIsCookiesValid(text!), NetscapeCookieFile.IsValidForVrcvc(text));
    }

    [Theory]
    [InlineData(".youtube.com\tTRUE\t/\tTRUE\t1893456000\tLOGIN_INFO\tv\n")]
    [InlineData(".youtube.com\tTRUE\t/\tTRUE\t0\tLOGIN_INFO\t\n")]
    [InlineData("youtube.com LOGIN_INFO")]
    public void IsValidForVrcvc_Accepts_ExactlyLikeUpstream(string text)
    {
        Assert.True(NetscapeCookieFile.IsValidForVrcvc(text));
        Assert.Equal(UpstreamIsCookiesValid(text), NetscapeCookieFile.IsValidForVrcvc(text));
    }

    [Fact]
    public void IsValidForVrcvc_AgreesWithUpstream_OnCanonicalizedJars()
    {
        var jars = new[]
        {
            TestJars.Build(),
            TestJars.BuildWithoutLogin(),
            TestJars.BuildForeignHost(),
            NetscapeCookieFile.Canonicalize(TestJars.Build()),
        };

        foreach (var jar in jars)
        {
            var canonical = NetscapeCookieFile.Canonicalize(jar);
            Assert.Equal(UpstreamIsCookiesValid(canonical), NetscapeCookieFile.IsValidForVrcvc(canonical));
        }
    }

    [Fact]
    public void IsUsable_RequiresParsableRowsToo()
    {
        // Passes the textual upstream check, but contains no parsable row.
        const string headerOnly = "# youtube.com LOGIN_INFO\n";

        Assert.True(NetscapeCookieFile.IsValidForVrcvc(headerOnly));
        Assert.False(NetscapeCookieFile.IsUsable(headerOnly));
        Assert.True(NetscapeCookieFile.IsUsable(TestJars.Build()));
    }

    // ---- Summarize ------------------------------------------------------

    [Fact]
    public void Summarize_CountsRowsAndDetectsLoginCookie()
    {
        var summary = NetscapeCookieFile.Summarize(NetscapeCookieFile.Canonicalize(TestJars.Build(extraCookies: 2)));

        Assert.Equal(5, summary.CookieCount);   // LOGIN_INFO + SID + HSID + 2 extras
        Assert.True(summary.LoginCookiePresent);
        Assert.True(summary.HasYoutubeDomain);
        Assert.Equal(64, summary.Sha256.Length);
    }

    [Fact]
    public void Summarize_ReportsExpiryWindow_OnlyForFutureCookies()
    {
        var text = Header +
                   TestJars.Row(".youtube.com", "LOGIN_INFO", "v", "/", TestJars.FutureExpiry) + "\n" +
                   TestJars.Row(".youtube.com", "SID", "v", "/", TestJars.LaterExpiry) + "\n" +
                   TestJars.Row(".youtube.com", "EXPIRED", "v", "/", TestJars.ExpiredExpiry) + "\n";

        var summary = NetscapeCookieFile.Summarize(text);

        Assert.Equal(3, summary.CookieCount);
        Assert.Equal(DateTimeOffset.FromUnixTimeSeconds(TestJars.FutureExpiry), summary.EarliestExpiryUtc);
        Assert.Equal(DateTimeOffset.FromUnixTimeSeconds(TestJars.LaterExpiry), summary.LatestExpiryUtc);
    }

    [Fact]
    public void Summarize_Empty_ReturnsEmptySummary()
    {
        var summary = NetscapeCookieFile.Summarize("");

        Assert.Equal(0, summary.CookieCount);
        Assert.False(summary.LoginCookiePresent);
        Assert.False(summary.HasYoutubeDomain);
        Assert.Null(summary.LatestExpiryUtc);
    }

    [Fact]
    public void Summarize_LoginCookiePresent_RequiresYoutubeDomain()
    {
        var summary = NetscapeCookieFile.Summarize(
            Header + TestJars.Row(".example.com", "LOGIN_INFO", "v") + "\n");

        Assert.Equal(1, summary.CookieCount);
        Assert.False(summary.LoginCookiePresent);
        Assert.False(summary.HasYoutubeDomain);
    }

    [Fact]
    public void Sha256Hex_IsStableLowercaseHex()
    {
        var a = NetscapeCookieFile.Sha256Hex("abc");
        var b = NetscapeCookieFile.Sha256Hex("abc");

        Assert.Equal(a, b);
        Assert.Equal(64, a.Length);
        Assert.Equal(a.ToLowerInvariant(), a);
        Assert.Equal("ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad", a);
    }
}
