# Real contract-mode verification: push a synthetic jar through the installed native host into
# %APPDATA%\VRCVideoCacher\youtube_cookies.txt, verify, then restore the previous state.
$ErrorActionPreference = 'Continue'
$log = 'C:\Users\lz200\Documents\deepseek-harness\default-workspace\VRCVideoCacher-CookieBridge\dist\_contract-test.txt'
Start-Transcript -Path $log -Force | Out-Null
try {
    $hostExe = Join-Path $env:LOCALAPPDATA 'VRCVideoCacher-CookieBridge\host\CookieBridge.NativeHost.exe'
    $target  = Join-Path $env:APPDATA 'VRCVideoCacher\youtube_cookies.txt'
    $fake    = Join-Path $env:TEMP 'cookiebridge_fake_jar.txt'

    $hadFile = Test-Path $target
    $backup  = $null
    if ($hadFile) {
        $backup = "$target.cookiebridge-preserve"
        Copy-Item $target $backup -Force
        "previous cookie file preserved at $backup"
    } else {
        "previous state: no cookie file (nothing to preserve)"
    }

    $rows = @(
        '# Netscape HTTP Cookie File',
        "# This file is generated by VRCVideoCacher.  Do not edit.",
        '',
        ".youtube.com`tTRUE`t/`tTRUE`t1790000000`tLOGIN_INFO`tFAKE_LOGIN_INFO_VALUE",
        ".youtube.com`tTRUE`t/`tTRUE`t1790000000`tSID`tFAKE_SID_VALUE",
        ".youtube.com`tTRUE`t/`tTRUE`t1790000000`t__Secure-1PSIDTS`tFAKE_PSIDTS",
        ".youtube.com`tTRUE`t/`tTRUE`t1790000000`tST-botcheck`tSHOULD_BE_DROPPED"
    )
    Set-Content -Path $fake -Value $rows -Encoding ASCII

    "`n=== host --send (real paths) ==="
    & $hostExe --send $fake
    "exit=$LASTEXITCODE"

    "`n=== target file state ==="
    if (Test-Path $target) {
        $bytes = (Get-Item $target).Length
        $lines = Get-Content $target
        "exists=True bytes=$bytes lines=$($lines.Count)"
        "contains LOGIN_INFO : $([bool]($lines -match 'LOGIN_INFO'))"
        "contains ST- row    : $([bool]($lines -match "`tST-"))"
        "field counts        : " + (($lines | Where-Object { $_ -and -not $_.StartsWith('#') } | ForEach-Object { ($_ -split "`t").Count }) -join ',')
        "`n--- content ---"
        $lines
    } else { 'MISSING (write failed)' }

    "`n=== vault (encrypted) ==="
    $vault = Join-Path $env:LOCALAPPDATA 'VRCVideoCacher-CookieBridge\vault.json'
    if (Test-Path $vault) {
        $doc = Get-Content $vault -Raw | ConvertFrom-Json
        "formatVersion=$($doc.formatVersion) protection=$($doc.protection) cookies=$($doc.metadata.cookieCount) login=$($doc.metadata.loginCookiePresent)"
        "payload is base64 and contains no plaintext: $(-not ($doc.payload -match 'LOGIN_INFO'))"
    } else { 'MISSING vault' }

    "`n=== bridge log ==="
    Get-Content (Join-Path $env:LOCALAPPDATA 'VRCVideoCacher-CookieBridge\logs\bridge.log') -Tail 6 -ErrorAction SilentlyContinue

    "`n=== restore ==="
    if ($hadFile) {
        Move-Item $backup $target -Force
        "restored previous cookie file"
    } else {
        Remove-Item $target -Force -ErrorAction SilentlyContinue
        "removed synthetic cookie file (was absent before the test): $(-not (Test-Path $target))"
    }
    Remove-Item $fake -Force -ErrorAction SilentlyContinue
}
catch { "EXCEPTION: $($_.Exception.Message)" }
finally { Stop-Transcript | Out-Null }
